"""Inventory the pinned real base set and all its climates, not an illustrative list.
NML expands templates; NFO records exact source rectangles and offsets.
GPL-2.0-only. No assets are generated by this inventory tool.
"""
import collections
import csv
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]; W=ROOT.parent; OG=W/'tools/sources/opengfx'; OUT=W/'artifacts/atelier/inventory'; OUT.mkdir(parents=True,exist_ok=True)
CLANG=W/'tools/llvm-mingw-20261020-ucrt-x86_64/bin/clang.exe'
refs=collections.defaultdict(list)
for p in OG.glob('sprites/**/*.pnml'):
    for line_no,line in enumerate(p.read_text(errors='replace').splitlines(),1):
        for name in re.findall(r'"(sprites/[^"\n]+\.png)"',line): refs[name].append(f'{p.relative_to(OG).as_posix()}:{line_no}')

project_path=W/'artifacts/assets/asset-build.json'
project={r['sprite']:r for r in json.loads(project_path.read_text())['coverage']} if project_path.exists() else {}
rows=[]; sets={}
for key,file in [('base','ogfx1_base'),('arctic','ogfxc_arctic'),('tropical','ogfxh_tropical'),('toyland','ogfxt_toyland'),('logos','ogfxi_logos'),('extra','ogfxe_extra')]:
    nml=OUT/(file+'.nml'); nfo=OUT/(file+'.nfo')
    subprocess.run([str(CLANG),'-E','-P','-x','c','-DNEWGRF_VERSION=8000','-I',str(OG),str(OG/(file+'.pnml')),'-o',str(nml)],check=True)
    if key=='extra':
        # NML 0.7.5 predates these Action5 labels. Inventory their real sprite
        # rectangles using a known block type; this NFO is never a game export.
        from nml.actions.action5 import action5_table
        unsupported=sorted(set(re.findall(r'replacenew(?:\s+\w+)?\s*\(\s*(\w+)',nml.read_text()))-set(action5_table))
        expanded=nml.read_text()
        for feature in unsupported: expanded=re.sub(r'(replacenew(?:\s+\w+)?\s*\(\s*)'+feature+r'\b',r'\1OTTD_GUI',expanded)
        nml.write_text(expanded)
        (OUT/'inventory-only-feature-normalization.json').write_text(json.dumps(unsupported))
    lang=OUT/'lang'; lang.mkdir(exist_ok=True)
    names=sorted(set(re.findall(r'\bSTR_[A-Z0-9_]+\b',nml.read_text())))
    (lang/'english.lng').write_text('##grflangid 0x01\n'+'\n'.join(n+':Inventory only' for n in names)+'\n')
    proc=subprocess.run([sys.executable,'-m','nml.main','--palette','DOS','--lang-dir',str(lang),'--nfo',str(nfo),str(nml)],cwd=OG,capture_output=True,text=True)
    (OUT/(file+'.log')).write_text(proc.stdout+proc.stderr)
    if proc.returncode: raise RuntimeError(file+': '+proc.stderr[-2000:])
    count=0
    for line in nfo.read_text().splitlines():
        m=re.match(r'^(\d+) (\S+\.png) (8bpp|32bpp) (-?\d+) (-?\d+) (\d+) (\d+) (-?\d+) (-?\d+) (\w+)(.*)',line)
        if not m: continue
        i=int(m[1]); f=m[2]; category=f.split('/')[2] if len(f.split('/'))>2 else 'other'
        scope='preserve-interface' if category in ('gui','fonts','logos','faces') or key=='logos' else 'world-replacement'
        row={'stable_id':f'opengfx:{key}:{i}','set':key,'sprite_id':i,'category':category,'source_file':f,'source_sha256':hashlib.sha256((OG/f).read_bytes()).hexdigest(),'source_references':refs[f], 'rect':list(map(int,m.groups()[3:9])),'depth':m[3],'zoom':m[10], 'flags':m[11].strip(),'footprint':'pixel dimensions in rect; world layout remains in engine table or cited PNML','required_views':'one exact runtime sprite slot; related direction/stage slots are separate manifest rows','animations_states':'preserve this slot and the original frame/callback timing','replacement':None,'integration':'inherited OpenGFX','validation':'source rectangle expanded by NML; replacement not produced','scope':scope}
        row['current_project_override']='renaissance-meadow.grf / '+project[i]['category'] if key=='base' and i in project else None
        rows.append(row); count+=1
    sets[key]={'raster_sprite_slots':count,'source':file+'.pnml','nfo_sha256':hashlib.sha256(nfo.read_bytes()).hexdigest()}
    print('INVENTORY',key,count,flush=True)

demo_path=W/'artifacts/atelier/demo-coverage.json'
demo=json.loads(demo_path.read_text()) if demo_path.exists() else []
replacements={r['stable_id']:r for r in demo}
for r in rows:
    if r['stable_id'] in replacements:
        d=replacements[r['stable_id']]; r.update(replacement=d['source_asset'],integration=d['integration'],validation='compiled 8bpp + 32bpp at 1x/2x/4x; runtime matrix in verification report')
with (OUT/'asset-manifest.csv').open('w',newline='',encoding='utf-8') as f:
    writer=csv.DictWriter(f,fieldnames=list(rows[0])); writer.writeheader(); writer.writerows(rows)
(OUT/'asset-manifest.json').write_text(json.dumps(rows,indent=2))
engines=[]
text=(ROOT/'src/table/engines.h').read_text()
for m in re.finditer(r'^\s*(M[TM WRS A]{1,2})\((.*?)\),\s*//\s*(\d+)\s+([^\n]+)',text,re.M):
    engines.append({'engine_id':int(m[3]),'name':m[4].strip(),'table_macro':m[1],'properties':m[2],'source':'src/table/engines.h','replacement':'demo' if int(m[3]) in (13,27,29,116,138,206) else 'inherited; awaiting full-production approval'})
(OUT/'vehicle-roster.json').write_text(json.dumps(engines,indent=2))
summary={'base_set':'OpenGFX 8.0','pinned_revision':'e68bd9b7cb60305aa98c687b6836e0e0b08e2847','sets':sets,'total_raster_slots':len(rows),'world_raster_slots':sum(r['scope']=='world-replacement' for r in rows),'interface_slots_preserved':sum(r['scope']=='preserve-interface' for r in rows),'demo_replaced_slots':len(replacements),'vehicle_roster_entries':len(engines),'counting_unit':'one normal raster sprite slot; directions, stages and load states are distinct slots, not distinct 3D models','extra_id_policy':'extra-set IDs are pinned compiled NFO slot IDs; never use them as ActionA replacement IDs','production_approved':False}
(OUT/'summary.json').write_text(json.dumps(summary,indent=2)); print(json.dumps(summary,indent=2))
